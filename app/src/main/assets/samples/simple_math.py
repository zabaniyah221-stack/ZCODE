# Simple Math — operasi matematika dasar + akar kuadrat ➕✖️
import math

a = 7
b = 3

print(a, "+", b, "=", a + b)
print(a, "-", b, "=", a - b)
print(a, "*", b, "=", a * b)
print(a, "/", b, "=", a / b)
print(a, "pangkat", b, "=", a ** b)
print("Akar dari", a, "=", round(math.sqrt(a), 4))
print("Pi itu cantik:", math.pi)
